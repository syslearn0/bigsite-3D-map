// 東展示棟のガレリア 1F（ホールの前の細長い通路）とリンクスペース：まず通路の向きにまっすぐな線を 2 本
// （ホールの出入口と南の列の階段のあいだ、2 列の階段のあいだ）、そのあと出入口・階段の下の端へ直角な線でつなぐ（ユーザーの指示）。
// 向かい合う階段とエスカレーターの下の端は、1 本の横切る線にまとめる
const G1_A = -13.3; // 出入口（v -15.5〜-17.7）と南の列の階段（v -11 から北）のあいだ
const G1_B = 6; // 2 列の階段のあいだ
const G1_LINES: XZ[][] = [
  // 南の線：西の端は、東1 の前の部屋（VIP ルーム・多目的室）が通路まで出ているので、その東から
  [g(12, G1_A), g(299.1, G1_A)],
  [g(0, G1_B), g(378, G1_B)],
];
const toUV = (p: XZ): [number, number] => [
  (p[0] - GO[0]) * GU[0] + (p[1] - GO[1]) * GU[1],
  (p[0] - GO[0]) * GV[0] + (p[1] - GO[1]) * GV[1],
];
{
  // 階段・エスカレーターの下の端（1F）。出る向き（上の端と反対）へ少し出た所を、横切る線の位置にする
  type Foot = { at: XZ; u: number; v: number; out: number };
  const feet: Foot[] = [];
  for (const st of (
    venueJson as unknown as {
      stairs: { to: XZ; from: XZ; toLevel: number; kind?: string }[];
    }
  ).stairs) {
    if (st.toLevel !== 1 || st.kind === "ramp") continue;
    const [u, v] = toUV(st.to),
      [ut] = toUV(st.from);
    if (u < -25 || u > 400 || v < -25 || v > 35) continue;
    feet.push({ at: st.to, u, v, out: u > ut ? 1 : -1 });
  }
  for (const north of [false, true]) {
    const row = feet
      .filter((f) => f.v > 10 === north)
      .sort((x, y) => x.u - y.u);
    // 向かい合う 2 つ（左は +u へ、右は -u へ出る。8m ほど離れている）は、まん中の 1 本に
    for (let k = 0; k < row.length; k++) {
      const f = row[k],
        h = row[k + 1];
      const pair =
        h && f.out === 1 && h.out === -1 && h.u - f.u < 12 ? [f, h] : [f];
      if (pair.length === 2) k++;
      const uc = pair.length === 2 ? (f.u + h.u) / 2 : f.u + f.out * 1.5;
      const vs = pair.map((x) => x.v).sort((x, y) => x - y);
      const cross = north ? [G1_B, ...vs] : [G1_A, ...vs, G1_B];
      G1_LINES.push(cross.map((v) => g(uc, v)));
      for (const x of pair) G1_LINES.push([x.at, g(uc, x.v)]);
    }
  }
  // 出入口から、いちばん近いまっすぐな線へ直角に（東1〜3 は南の線へ、東7・8 はリンクスペースの線へ）
  for (const d of (
    venueJson as unknown as { doors: { at: XZ; hall: string; kind: string }[] }
  ).doors) {
    if (d.kind !== "出入口" || !["E1", "E2", "E3", "E7", "E8"].includes(d.hall))
      continue;
    const [u] = toUV(d.at);
    if (d.hall === "E7" && u < 310)
      G1_LINES.push([g(u, G1_A), g(u, G1_B), d.at]);
    // 西の端の出入口（東1）は、前に部屋があるので、ここでは引かない（出入口の近くの線へは、地図を読むときにつなぐ）
    else if (u < 12) continue;
    else
      G1_LINES.push([d.at, g(u, ["E7", "E8"].includes(d.hall) ? G1_B : G1_A)]);
  }
}
